import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { readArtifact } from "./artifact.mjs";

const artifact = await readArtifact();
const { resource, manifest } = artifact;
const config = JSON.parse(readFileSync("pbiviz.json", "utf8"));
assert.equal(resource.visual.guid, "AtlynFinancialMatrixCA42B8646E934AF1B6252CB8E39C0D71");
assert.deepEqual(resource.visual, config.visual);
assert.deepEqual(manifest.visual, resource.visual);
assert.equal(resource.apiVersion, "5.11.0");
assert.deepEqual(resource.capabilities, JSON.parse(readFileSync("capabilities.json", "utf8")));
assert.deepEqual(resource.capabilities.privileges, []);
assert.deepEqual(resource.externalJS, []);
assert.ok(resource.content.js.length > 1000, "Missing production JS");
assert.ok(resource.content.css.includes(".afm"), "Missing production CSS");
assert.ok(resource.stringResources["en-US"]?.Role_Actual, "Missing English strings");
assert.ok(resource.stringResources["fr-FR"]?.Role_Actual, "Missing French strings");
assert.equal(resource.stringResources["en-US"].ThirdParty_Notices, readFileSync("THIRD-PARTY-NOTICES.txt", "utf8"), "Packaged OSS notices missing or stale");
assert.ok(!JSON.stringify(resource).includes("-----BEGIN PRIVATE KEY-----"), "Private key must not be packaged");
const icon = Buffer.from(resource.content.iconBase64.replace(/^data:image\/png;base64,/, ""), "base64");
assert.ok(icon.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10])), "Icon is not PNG");
assert.equal(icon.readUInt32BE(16), 20);
assert.equal(icon.readUInt32BE(20), 20);
const report = { path: artifact.path, sha256: artifact.sha256, bytes: artifact.size, guid: resource.visual.guid, version: resource.visual.version };
writeFileSync("dist/artifact-validation.json", JSON.stringify(report, null, 2) + "\n");
writeFileSync(`${artifact.path}.sha256`, `${artifact.sha256}  ${artifact.path.split(/[\\/]/).pop()}\n`);
console.log(JSON.stringify(report, null, 2));
